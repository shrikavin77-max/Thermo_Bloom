import type { SimulationState, SiteData, AIRecommendation, SystemAlert, HistoryPoint } from '../types';

/**
 * Calculates updated simulation outputs given current sliders and active site.
 */
export function calculateSimulationOutputs(
  state: SimulationState,
  site: SiteData,
  currentBiomassGramsPerLiter: number,
  biomassAccumulatedTodayKg: number
): {
  state: SimulationState;
  recommendations: AIRecommendation[];
  alerts: SystemAlert[];
} {
  const {
    serverLoad,
    coolantInletTemp,
    coolantFlowRate,
    ambientTemp,
    lightIntensity,
    co2Level,
    nutrientLevel,
    waterRecirculationRate,
  } = state;

  // 1. Thermal calculation
  // Waste heat generated by servers in kW:
  // Base server capacity in kW * (serverLoad / 100) * 0.92 (approx 92% power turns to heat)
  const serverCapacityKW = site.serverCapacityMW * 1000;
  const wasteHeatAvailableKW = Math.round(serverCapacityKW * (serverLoad / 100) * 0.92);

  // Heat absorbed by bioreactor heat exchanger
  // Depends on coolant inlet temp, coolant flow rate, and delta T with ambient/reactor
  // Transfer efficiency ~ 45% - 75% depending on flow rate
  const flowEfficiency = Math.min(0.85, 0.40 + (coolantFlowRate / 100) * 0.40);
  const tempDeltaDriving = Math.max(0, coolantInletTemp - 20);
  // Max heat reactor can absorb without boiling
  const reactorAbsorptiveCapacityKW = Math.round((site.reactorVolumeLiters / 1000) * 22);
  const theoreticalHeatTransferKW = Math.round(wasteHeatAvailableKW * flowEfficiency * (tempDeltaDriving / 25));
  const heatAbsorbedKW = Math.min(reactorAbsorptiveCapacityKW, theoreticalHeatTransferKW);
  const heatRejectedKW = Math.max(0, wasteHeatAvailableKW - heatAbsorbedKW);
  
  // Cooling energy offset % (energy chiller would have had to consume, COP ~ 3.8)
  const coolingEnergyOffsetPercent = Number(
    Math.min(32, Math.max(5, (heatAbsorbedKW / wasteHeatAvailableKW) * 100 * 0.45)).toFixed(1)
  );

  // Reactor Water Temp (°C)
  // Base water temperature is influenced by ambient temp + heat absorbed scaled by volume
  const thermalLoadFactor = heatAbsorbedKW / (site.reactorVolumeLiters / 1000 * 4.184 * 0.28);
  const unmoderatedTemp = 0.65 * ambientTemp + 0.35 * coolantInletTemp + thermalLoadFactor * 0.32;
  // Water recirculation cools slightly (evaporative / heat exchange dissipation)
  const recirculationCooling = (waterRecirculationRate / 100) * 3.5;
  const reactorWaterTemp = Number(Math.max(16, Math.min(46, unmoderatedTemp - recirculationCooling)).toFixed(1));

  // 2. Algae Photosynthesis and Growth Kinetics
  // Optimal temp range: 22°C - 32°C. Peaks around 27°C.
  let tempFactor = 0.1;
  if (reactorWaterTemp >= 16 && reactorWaterTemp <= 22) {
    tempFactor = 0.3 + ((reactorWaterTemp - 16) / 6) * 0.5; // 0.3 to 0.8
  } else if (reactorWaterTemp > 22 && reactorWaterTemp <= 32) {
    // peak optimal curve
    const deviation = Math.abs(reactorWaterTemp - 27);
    tempFactor = 1.0 - (deviation / 10) * 0.2; // 0.8 to 1.0
  } else if (reactorWaterTemp > 32 && reactorWaterTemp <= 35) {
    tempFactor = 0.8 - ((reactorWaterTemp - 32) / 3) * 0.45; // drops to 0.35
  } else if (reactorWaterTemp > 35) {
    // Thermal stress decline
    tempFactor = Math.max(0.05, 0.35 - ((reactorWaterTemp - 35) / 5) * 0.30);
  }

  // Light factor (Monod kinetics with photoinhibition at extreme light > 750)
  // Optimal light: 400 - 650 µmol/m²/s
  let lightFactor = 0;
  if (lightIntensity < 50) {
    lightFactor = lightIntensity / 100;
  } else if (lightIntensity <= 650) {
    lightFactor = 0.5 + ((lightIntensity - 50) / 600) * 0.5;
  } else {
    // Photoinhibition slight drop
    lightFactor = 1.0 - ((lightIntensity - 650) / 150) * 0.18;
  }

  // CO2 factor (Monod saturation: optimal ~ 600 - 950 ppm, diminishing returns above)
  let co2Factor = 0.2;
  if (co2Level < 400) {
    co2Factor = 0.3 + (co2Level / 400) * 0.35;
  } else if (co2Level <= 950) {
    co2Factor = 0.65 + ((co2Level - 400) / 550) * 0.35;
  } else {
    // saturated
    co2Factor = 1.0;
  }

  // Nutrient factor (Michaelis-Menten kinetics, optimal 50% - 85%. Too high causes toxicity)
  let nutrientFactor = 0.4;
  if (nutrientLevel < 40) {
    nutrientFactor = 0.4 + (nutrientLevel / 40) * 0.4;
  } else if (nutrientLevel <= 85) {
    nutrientFactor = 0.8 + ((nutrientLevel - 40) / 45) * 0.2;
  } else {
    // slight toxicity penalty
    nutrientFactor = 1.0 - ((nutrientLevel - 85) / 15) * 0.15;
  }

  // Combined Specific Growth Rate (g/L/day)
  // Maximum theoretical growth rate is ~ 1.85 g/L/day for Chlorella/Spirulina in optimized photobioreactor
  const maxGrowthRate = 1.85;
  const growthKinetics = tempFactor * lightFactor * co2Factor * nutrientFactor;
  const algaeGrowthRate = Number((maxGrowthRate * growthKinetics).toFixed(2));

  // Culture Health Score calculation (0 - 100)
  let health = 100;
  // Temp penalties
  if (reactorWaterTemp > 35) {
    health -= (reactorWaterTemp - 35) * 12;
  } else if (reactorWaterTemp > 32) {
    health -= (reactorWaterTemp - 32) * 5;
  } else if (reactorWaterTemp < 20) {
    health -= (20 - reactorWaterTemp) * 4;
  }
  // CO2 penalties
  if (co2Level < 350) health -= 12;
  // Nutrient penalties
  if (nutrientLevel > 90) health -= 10;
  if (nutrientLevel < 25) health -= 15;
  // Light penalties
  if (lightIntensity < 100) health -= 14;
  // Clamped health
  const cultureHealthScore = Math.round(Math.max(12, Math.min(100, health)));

  // pH calculation (photosynthesis consumes dissolved CO2/carbonic acid raising pH; low CO2 increases pH)
  // Normal range: 7.2 - 8.4
  const basePH = 7.6;
  const co2AcidityShift = -((co2Level - 600) / 600) * 0.6;
  const growthAlkalinityShift = (algaeGrowthRate / maxGrowthRate) * 0.4;
  const phValue = Number(Math.max(6.2, Math.min(9.4, basePH + co2AcidityShift + growthAlkalinityShift)).toFixed(2));

  // Dissolved Oxygen (mg/L)
  // Warmer water holds less DO, active photosynthesis produces DO (6 - 12 mg/L)
  const baseDO = 10.5 - (reactorWaterTemp - 20) * 0.15;
  const photosyntheticDO = (algaeGrowthRate / maxGrowthRate) * 2.8;
  const dissolvedOxygenMgL = Number(Math.max(3.8, Math.min(14.5, baseDO + photosyntheticDO)).toFixed(1));

  // Harvest readiness (based on current biomass density vs target density ~ 2.4 g/L)
  const targetHarvestDensity = 2.4;
  const harvestReadinessPercent = Math.round(
    Math.min(100, (currentBiomassGramsPerLiter / targetHarvestDensity) * 100)
  );

  // Optical Density OD680
  const opticalDensityOD680 = Number((currentBiomassGramsPerLiter * 0.92).toFixed(2));

  // CO2 Uptake Rate:
  // 1 kg dry algae biomass requires ~ 1.83 kg CO2
  // Wet/fresh biomass is ~ 10-15% dry weight.
  const co2UptakeRateKgDay = Number(((algaeGrowthRate * (site.reactorVolumeLiters / 1000) * 1.83) * 0.95).toFixed(1));
  const co2UptakeGramsPerHour = Math.round((co2UptakeRateKgDay * 1000) / 24);

  // System status determination
  let statusMode: SimulationState['statusMode'] = 'optimal';
  if (cultureHealthScore < 45 || reactorWaterTemp >= 36) {
    statusMode = 'critical';
  } else if (cultureHealthScore < 75 || reactorWaterTemp > 32 || phValue > 8.8 || phValue < 6.8) {
    statusMode = 'warning';
  }

  // 3. AI Rule-based Recommendations
  const recommendations: AIRecommendation[] = [];
  const nowStr = new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });

  if (reactorWaterTemp > 33) {
    recommendations.push({
      id: 'rec-temp-high',
      category: 'temperature',
      title: 'Thermal Regulation: Divert Server Heat',
      description: `Bioreactor temperature (${reactorWaterTemp}°C) is above optimal range (22-32°C). Culture health is declining.`,
      reasoning: 'Excessive heat denatures RuBisCO photosynthetic enzymes and causes heat-shock mortality in algae.',
      actionText: 'Reduce Coolant Flow by 15%',
      actionPatch: { coolantFlowRate: Math.max(15, coolantFlowRate - 15) },
      severity: reactorWaterTemp > 35 ? 'urgent' : 'warning',
      timestamp: nowStr,
    });
  } else if (reactorWaterTemp < 22) {
    recommendations.push({
      id: 'rec-temp-low',
      category: 'temperature',
      title: 'Thermal Enrichment: Channel Server Waste Heat',
      description: `Bioreactor temperature (${reactorWaterTemp}°C) is sub-optimal. Algae metabolic activity is sluggish.`,
      reasoning: 'Increasing warm coolant circulation transfers available server heat to reach peak 26-28°C biological kinetic velocity.',
      actionText: 'Increase Coolant Flow to 75 L/min',
      actionPatch: { coolantFlowRate: Math.min(95, coolantFlowRate + 20) },
      severity: 'tip',
      timestamp: nowStr,
    });
  }

  if (lightIntensity < 400 && cultureHealthScore > 60) {
    recommendations.push({
      id: 'rec-light-boost',
      category: 'light',
      title: 'Photobioreactor Boost: Increase Photon Flux',
      description: `Light intensity (${lightIntensity} µmol/m²/s) is below photosynthetic saturation threshold.`,
      reasoning: 'Adding 80-120 µmol/m²/s will accelerate light-dependent ATP and NADPH synthesis, raising growth rate by ~24%.',
      actionText: 'Increase Light by +80 µmol/m²/s',
      actionPatch: { lightIntensity: Math.min(750, lightIntensity + 80) },
      severity: 'tip',
      timestamp: nowStr,
    });
  }

  if (co2Level < 500) {
    recommendations.push({
      id: 'rec-co2-low',
      category: 'co2',
      title: 'Carbon Enrichment: Increase CO2 Dosing',
      description: `Dissolved CO2 is sub-optimal (${co2Level} ppm). Photosynthesis is carbon-limited.`,
      reasoning: 'Algae requires ~1.83 kg CO2 per kg dry biomass. Increasing injection restores carbonic buffer and prevents high pH stress.',
      actionText: 'Enrich CO2 to 780 ppm',
      actionPatch: { co2Level: 780 },
      severity: 'warning',
      timestamp: nowStr,
    });
  } else if (co2Level > 1100) {
    recommendations.push({
      id: 'rec-co2-high',
      category: 'co2',
      title: 'CO2 Moderation: Diminishing Carbon Returns',
      description: `CO2 level (${co2Level} ppm) is exceeding saturation kinetics with risk of mild acidification.`,
      reasoning: 'Diminishing biological returns above 950 ppm waste injected gas without increasing biomass velocity.',
      actionText: 'Trim CO2 to 850 ppm',
      actionPatch: { co2Level: 850 },
      severity: 'tip',
      timestamp: nowStr,
    });
  }

  if (nutrientLevel > 88) {
    recommendations.push({
      id: 'rec-nutrient-excess',
      category: 'nutrients',
      title: 'Nutrient Balance: Pause Dosing Cycle',
      description: `Nutrient saturation at ${nutrientLevel}%. High nitrate/phosphate can trigger osmotic stress.`,
      reasoning: 'Pausing dosing for 4 hours allows cellular assimilation and prevents biofilm fouling on reactor walls.',
      actionText: 'Reset Nutrients to 70%',
      actionPatch: { nutrientLevel: 70 },
      severity: 'warning',
      timestamp: nowStr,
    });
  }

  if (harvestReadinessPercent >= 85) {
    recommendations.push({
      id: 'rec-harvest-ready',
      category: 'harvest',
      title: 'Harvest Recommended: Peak Biomass Density',
      description: `Current culture concentration is ${currentBiomassGramsPerLiter.toFixed(2)} g/L (${harvestReadinessPercent}% ready).`,
      reasoning: 'Self-shading will soon decelerate growth kinetics. Harvesting 60-70% biomass now maintains exponential growth phase.',
      actionText: 'Initiate Semi-Continuous Harvest',
      severity: 'tip',
      timestamp: nowStr,
    });
  }

  // 4. System Alerts
  const alerts: SystemAlert[] = [];

  if (reactorWaterTemp > 34) {
    alerts.push({
      id: 'alert-temp-crit',
      type: 'temperature',
      severity: 'critical',
      title: 'ALGAE HEAT STRESS — COOLING BYPASS ENGAGED',
      message: `Reactor liquid core reached ${reactorWaterTemp}°C. AI automated solenoid bypass valve opened to divert excess heat.`,
      metric: `${reactorWaterTemp}°C (Safe: 22-32°C)`,
      timestamp: nowStr,
    });
  } else if (reactorWaterTemp > 31) {
    alerts.push({
      id: 'alert-temp-warn',
      type: 'temperature',
      severity: 'warning',
      title: 'Elevated Temperature Advisory',
      message: `Reactor water temperature elevated to ${reactorWaterTemp}°C. Approaching upper thermal threshold.`,
      metric: `${reactorWaterTemp}°C`,
      timestamp: nowStr,
    });
  }

  if (phValue < 6.8 || phValue > 8.8) {
    alerts.push({
      id: 'alert-ph-out',
      type: 'ph',
      severity: 'warning',
      title: 'pH Out of Optimal Envelope',
      message: `Current pH is ${phValue}. Adjust CO2 injection to rebalance carbonate buffer.`,
      metric: `pH ${phValue} (Target: 7.2 - 8.4)`,
      timestamp: nowStr,
    });
  }

  if (co2Level < 400) {
    alerts.push({
      id: 'alert-co2-low',
      type: 'co2',
      severity: 'warning',
      title: 'Low Carbon Dioxide Supply',
      message: `Inlet CO2 concentration at ${co2Level} ppm limits photosynthetic dark reactions.`,
      metric: `${co2Level} ppm`,
      timestamp: nowStr,
    });
  }

  if (nutrientLevel > 90) {
    alerts.push({
      id: 'alert-nutrient-high',
      type: 'nutrient',
      severity: 'warning',
      title: 'Nutrient Overdosing Alert',
      message: `Nutrient dosing is at ${nutrientLevel}%, causing excess salinity and culture foaming.`,
      metric: `${nutrientLevel}%`,
      timestamp: nowStr,
    });
  } else if (nutrientLevel < 25) {
    alerts.push({
      id: 'alert-nutrient-low',
      type: 'nutrient',
      severity: 'warning',
      title: 'Nutrient Depletion Advisory',
      message: 'Nitrogen & phosphorus reserves depleted; chlorosis risk detected.',
      metric: `${nutrientLevel}%`,
      timestamp: nowStr,
    });
  }

  if (currentBiomassGramsPerLiter < 0.35) {
    alerts.push({
      id: 'alert-density-low',
      type: 'density',
      severity: 'info',
      title: 'Inoculation Phase / Low Density',
      message: 'Algae cell concentration is in lag/early phase. Photoprotective LED modulation active.',
      metric: `${currentBiomassGramsPerLiter.toFixed(2)} g/L`,
      timestamp: nowStr,
    });
  }

  if (heatAbsorbedKW >= reactorAbsorptiveCapacityKW * 0.95) {
    alerts.push({
      id: 'alert-cooling-max',
      type: 'cooling',
      severity: 'warning',
      title: 'Heat Exchanger Saturated',
      message: 'Bioreactor heat recovery at 95%+ thermal saturation. Diverting excess to secondary cooling loop.',
      metric: `${heatAbsorbedKW} kW / ${reactorAbsorptiveCapacityKW} kW`,
      timestamp: nowStr,
    });
  }

  const updatedState: SimulationState = {
    ...state,
    wasteHeatAvailableKW,
    heatAbsorbedKW,
    heatRejectedKW,
    coolingEnergyOffsetPercent,
    reactorWaterTemp,
    algaeGrowthRate,
    currentBiomassGramsPerLiter,
    biomassAccumulatedTodayKg,
    co2UptakeRateKgDay,
    co2UptakeGramsPerHour,
    dissolvedOxygenMgL,
    phValue,
    cultureHealthScore,
    harvestReadinessPercent,
    opticalDensityOD680,
    statusMode,
  };

  return { state: updatedState, recommendations, alerts };
}

/**
 * Generates initial 24-hour historical trend points for the active site
 */
export function generate24HourHistory(baseBiomass: number, baseGrowthRate: number, baseHeat: number): HistoryPoint[] {
  const points: HistoryPoint[] = [];
  const hours = 24;
  
  for (let i = 0; i <= hours; i++) {
    const hourLabel = `${(i < 10 ? '0' : '') + i}:00`;
    // Diurnal variation in growth (higher during middle hours)
    const diurnalFactor = 0.5 + 0.5 * Math.sin(((i - 6) / 18) * Math.PI);
    const growth = Number(Math.max(0.2, baseGrowthRate * (0.6 + 0.4 * diurnalFactor)).toFixed(2));
    const accumulated = Number((baseBiomass * (0.35 + (i / hours) * 0.65)).toFixed(2));
    const heatAbs = Math.round(baseHeat * (0.8 + 0.25 * Math.sin((i / 24) * 2 * Math.PI)));
    const heatRej = Math.round(heatAbs * 0.55);
    
    points.push({
      time: hourLabel,
      biomass: accumulated,
      growthRate: growth,
      heatAbsorbed: heatAbs,
      heatRejected: heatRej,
      temp: Number((25.5 + 2.5 * Math.sin((i / 24) * 2 * Math.PI)).toFixed(1)),
      co2Uptake: Number((growth * 16.2).toFixed(1)),
      health: Math.min(100, Math.round(88 + 8 * Math.cos((i / 12) * Math.PI))),
    });
  }

  return points;
}

